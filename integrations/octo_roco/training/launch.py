def launch_octo_training(cfg: OctoTrainingConfig) -> LaunchResult:
    """Convert demos, write configs, launch Octo fine-tune, return manifest."""
    run_dir = Path(cfg.checkpoint_dir)
    manifest_path = str(run_dir / "run_manifest.json")

    if run_dir.exists() and (run_dir / "run_manifest.json").exists() and not cfg.overwrite:
        existing = json.loads((run_dir / "run_manifest.json").read_text())
        if existing.get("status") not in ("failed", "dry_run"):
            raise OctoLaunchError(
                f"Run directory already exists: {run_dir}. "
                "Use overwrite=True to re-run."
            )

    run_dir.mkdir(parents=True, exist_ok=True)

    # 1. Convert dataset (skip in dry-run)
    rlds_dir = cfg.resolved_rlds_dir
    if cfg.dry_run:
        print(f"  [1/3] Skipping dataset conversion (dry-run).")
        dataset_meta: Dict[str, Any] = {"backend": "dry_run"}
    else:
        print(f"  [1/3] Converting demos → RLDS ...")
        from integrations.octo_roco.dataset_converter import convert_demos
        convert_result = convert_demos(
            data_root=cfg.resolved_data_root,
            output_dir=rlds_dir,
            task_id=cfg.task_id,
            skill_id=cfg.skill_id,
            agent_name=cfg.agent_name,
            language_instruction=cfg.language_instruction,
            val_fraction=cfg.val_fraction,
            action_dim=cfg.action_dim,
            state_dim=cfg.state_dim,
        )
        print(f"       train={convert_result.num_train_episodes} eps  "
              f"val={convert_result.num_val_episodes} eps  "
              f"backend={convert_result.backend}")
        dataset_meta = {
            "num_train_episodes": convert_result.num_train_episodes,
            "num_val_episodes": convert_result.num_val_episodes,
            "total_steps": convert_result.total_steps,
            "backend": convert_result.backend,
        }

    # 2. Write finetune config file
    print(f"  [2/3] Writing Octo finetune config ...")
    config_file = str(run_dir / "finetune_config.py")
    finetune_cfg_str = _generate_finetune_config(cfg, rlds_dir)
    Path(config_file).write_text(finetune_cfg_str)

    # 3. Build command
    command = _build_command(cfg, config_file, str(run_dir))
    print(f"  [3/3] Training command:\n        {' '.join(command)}")

    # Write initial manifest
    manifest: Dict[str, Any] = {
        "name": cfg.name,
        "task_id": cfg.task_id,
        "skill_id": cfg.skill_id,
        "agent_name": cfg.agent_name,
        "pretrained_path": cfg.pretrained_path,
        "rlds_dir": rlds_dir,
        "checkpoint_dir": str(run_dir),
        "command": command,
        "config": cfg.to_dict(),
        "dataset": dataset_meta,
        "created_utc": _utc_now(),
        "status": "pending",
    }
    _write_json(manifest_path, manifest)

    if cfg.dry_run:
        manifest["status"] = "dry_run"
        manifest["end_utc"] = _utc_now()
        _write_json(manifest_path, manifest)
        print(f"\n  [dry_run] Would run: {' '.join(command)}")
        return LaunchResult(
            checkpoint_dir=str(run_dir),
            manifest_path=manifest_path,
            command=command,
            status="dry_run",
        )

    if command[1].startswith("<"):
        raise OctoLaunchError(
            "Could not find upstream Octo finetune script. Set "
            "OctoTrainingConfig.octo_repo_dir, OctoTrainingConfig.finetune_script, "
            "OCTO_REPO_DIR, or OCTO_FINETUNE_SCRIPT to an octo-models/octo checkout."
        )

    # 4. Run training
    manifest["status"] = "running"
    manifest["start_utc"] = _utc_now()
    _write_json(manifest_path, manifest)

    logs_dir = run_dir / "logs"
    logs_dir.mkdir(exist_ok=True)
    log_file = str(logs_dir / "train.log")
    print(f"\n  Training ... (log: {log_file})")

    try:
        env = os.environ.copy()
        compat_dir = Path(__file__).resolve().parents[1] / "upstream_compat"
        existing_pythonpath = env.get("PYTHONPATH", "")
        env["PYTHONPATH"] = (
            str(compat_dir)
            if not existing_pythonpath
            else str(compat_dir) + os.pathsep + existing_pythonpath
        )
        with open(log_file, "w") as log_fh:
            proc = subprocess.run(
                command,
                stdout=log_fh,
                stderr=subprocess.STDOUT,
                check=False,
                env=env,
            )
        returncode = proc.returncode
    except FileNotFoundError:
        raise OctoLaunchError(
            "Could not find upstream Octo 'scripts/finetune.py'. "
            "Set OCTO_REPO_DIR or OCTO_FINETUNE_SCRIPT."
        )

    status = "completed" if returncode == 0 else "failed"
    manifest["status"] = status
    manifest["end_utc"] = _utc_now()
    manifest["returncode"] = returncode
    _write_json(manifest_path, manifest)

    if returncode != 0:
        raise OctoLaunchError(
            f"Octo finetune exited with code {returncode}. "
            f"See log: {log_file}"
        )

    print(f"  Training complete. Checkpoint: {run_dir}")
    return LaunchResult(
        checkpoint_dir=str(run_dir),
        manifest_path=manifest_path,
        command=command,
        status=status,
        num_steps_completed=cfg.num_steps,
    )


def launch_from_config_path(path: str) -> LaunchResult:
    from .config import load_octo_training_config
    return launch_octo_training(load_octo_training_config(path))
